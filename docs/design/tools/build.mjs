function dart(n, d, prev, parent) {
  if (!KNOWN.has(n.t)) return `${ind(d)}const SizedBox.shrink()`;
  const w = (code) => (n.x && parent ? `${ind(d)}Expanded(\n${ind(d + 1)}child: ${code.trimStart()},\n${ind(d)})` : code);
  const kids = (dd, par) => (n.c || []).map((c, i) => dart(c, dd, n.c[i - 1], par)).join(',\n') + ((n.c || []).length ? ',' : '');
  const list = (par) => `[\n${kids(d + 2, par)}\n${ind(d + 1)}]`;
  const dv = prev && prev.t === n.t;
  const I = (name) => `Icons.${ic(name)[1]}`;
  const P = (...a) => a.filter(Boolean).join(', ');
  switch (n.t) {
    case 'col': case 'row': {
      const main = n.t === 'row' ? (n.justify ? `mainAxisAlignment: MainAxisAlignment.${{ between: 'spaceBetween', center: 'center', end: 'end', start: 'start' }[n.justify]}` : '') : '';
      const cross = n.t === 'col' ? `crossAxisAlignment: CrossAxisAlignment.${{ start: 'start', center: 'center', end: 'end', stretch: 'stretch' }[n.align || 'stretch']}` : `crossAxisAlignment: CrossAxisAlignment.${{ start: 'start', center: 'center', end: 'end', stretch: 'stretch' }[n.align || 'center']}`;
      let code = `${ind(d)}${n.t === 'col' ? 'Column' : 'Row'}(\n${ind(d + 1)}${P(cross, main, n.gap != null ? `spacing: ${sp(n.gap)}` : '')},\n${ind(d + 1)}children: ${list(n.t)},\n${ind(d)})`;
      if (n.pad != null) { const inner = dart({ ...n, pad: undefined, x: false }, d + 1, prev, parent); code = `${ind(d)}Padding(\n${ind(d + 1)}padding: ${padDart(n.pad)},\n${ind(d + 1)}child: ${inner.trimStart()},\n${ind(d)})`; }
      return w(code);
    }
    case 'card': return w(`${ind(d)}THCard(\n${ind(d + 1)}${P(n.tone && n.tone !== 'default' ? `tone: THCardTone.${n.tone}` : '', n.pad != null ? `padding: ${sp(n.pad)}` : '')}${n.tone || n.pad != null ? ',' : ''}\n${ind(d + 1)}children: ${list('col')},\n${ind(d)})`);
    case 'hero': return w(`${ind(d)}THHero(\n${ind(d + 1)}children: ${list('col')},\n${ind(d)})`);
    case 'grid': return w(`${ind(d)}THGrid(\n${ind(d + 1)}columns: ${n.cols},\n${ind(d + 1)}spacing: ${sp(n.gap)},\n${ind(d + 1)}children: ${list('grid')},\n${ind(d)})`);
    case 'text': return w(`${ind(d)}THText(${ds(n.v)}, ${P(`style: THTextStyle.${n.s}`, n.tone && n.tone !== 'default' ? `tone: ${tone(n.tone)}` : '', n.align ? `align: TextAlign.${n.align === 'end' ? 'end' : n.align}` : '', n.size ? `size: ${Number(n.size).toFixed(1)}` : '', n.bold ? 'bold: true' : '')})`);
    case 'icon': return w(`${ind(d)}THIcon(${I(n.n)}, ${P(n.size ? `size: ${Number(n.size).toFixed(1)}` : '', n.tone && n.tone !== 'default' ? `tone: ${tone(n.tone)}` : '')})`.replace(', )', ')'));
    case 'btn': return w(`${ind(d)}THButton(\n${ind(d + 1)}label: ${ds(n.v)},\n${ind(d + 1)}kind: THButtonKind.${n.k},${n.sz === 'sm' ? `\n${ind(d + 1)}size: THButtonSize.sm,` : ''}${n.ic ? `\n${ind(d + 1)}icon: ${I(n.ic)},` : ''}${n.w === 'auto' ? `\n${ind(d + 1)}fullWidth: false,` : ''}\n${ind(d + 1)}onPressed: () {},\n${ind(d)})`);
    case 'ibtn': return w(`${ind(d)}THIconButton(icon: ${I(n.ic)}, kind: THButtonKind.${n.k}${n.dot ? ', dot: true' : ''}, semanticLabel: ${ds(n.ic)}, onPressed: () {})`);
    case 'badge': return w(`${ind(d)}THBadge(${ds(n.v)}, kind: THBadgeKind.${n.k}${n.ic ? (n.ic === 'dot' ? ', dot: true' : `, icon: ${I(n.ic)}`) : ''})`);
    case 'avatar': return w(`${ind(d)}THAvatar(${ds(n.v)}, size: THAvatarSize.${n.sz}${n.inv ? ', inverse: true' : ''})`);
    case 'field': return w(`${ind(d)}THField(${P(n.l ? `label: ${ds(n.l)}` : '', `value: ${ds(n.v)}`, n.ic ? `icon: ${I(n.ic)}` : '', n.tr ? `trailing: ${I(n.tr)}` : '', n.h ? `height: ${Number(n.h).toFixed(1)}` : '', n.ph ? 'placeholder: true' : '')})`);
    case 'pills': return w(`${ind(d)}THPills(items: [${n.items.map((p) => `THPillItem(${ds(p.v)}${p.on ? ', selected: true' : ''}${p.ic ? `, icon: ${I(p.ic)}` : ''})`).join(', ')}])`);
    case 'seg': return w(`${ind(d)}THSegmented(items: [${n.items.map(ds).join(', ')}], selected: ${n.on})`);
    case 'kv': return w(`${ind(d)}THKeyValue(${P(ds(n.l), ds(n.v), n.b ? 'bold: true' : '', n.strong ? 'strong: true' : '', n.tone ? `tone: ${tone(n.tone)}` : '', n.badge ? `badge: THBadgeKind.${n.badge === true ? 'brand' : n.badge === 'ok' ? 'ok' : 'accent'}` : '', n.copy ? 'copy: true' : '', dv ? 'divider: true' : '')})`);
    case 'prog': return w(`${ind(d)}THProgress(steps: ${n.steps}, done: ${n.done}${n.cur ? ', current: true' : ''})`);
    case 'dots': return w(`${ind(d)}THDots(count: ${n.count}, on: ${n.on})`);
    case 'dash': return w(`${ind(d)}THDashBox(icon: ${I(n.ic)}, title: ${ds(n.v)}${n.sub ? `, subtitle: ${ds(n.sub)}` : ''})`);
    case 'ring': return w(`${ind(d)}THRing(value: ${ds(n.v)}, caption: ${ds(n.sub)}, percent: ${(n.pct / 100).toFixed(2)})`);
    case 'sw': return w(`${ind(d)}THSwitch(on: ${n.on})`);
    case 'bubble': return w(`${ind(d)}THBubble(${ds(n.v)}, mine: ${n.mine}, time: ${ds(n.time)})`);
    case 'tile': return w(`${ind(d)}THTile(${I(n.ic)}${n.v ? `, label: ${ds(n.v)}` : ''}${n.big ? ', big: true' : ''}${n.tone ? `, tone: THBadgeKind.${n.tone}` : ''})`);
    case 'illus': return w(`${ind(d)}THIllustration(${I(n.ic)})`);
    case 'otp': return w(`${ind(d)}THOtp(count: ${n.count}, value: ${ds(n.v)})`);
    case 'bars': return w(`${ind(d)}THBars(values: [${n.vals.join(', ')}], labels: [${n.labels.map(ds).join(', ')}])`);
    case 'map': return w(`${ind(d)}const THMapPlaceholder()`);
    case 'stars': return w(`${ind(d)}THStars(${n.v}${n.size ? `, size: ${Number(n.size).toFixed(1)}` : ''})`);
    case 'listrow': return w(`${ind(d)}THListRow(${P(`icon: ${I(n.ic)}`, `title: ${ds(n.v)}`, n.sub ? `subtitle: ${ds(n.sub)}` : '', n.badge ? `badge: ${ds(n.badge)}` : '', n.dot ? 'unread: true' : '', n.flat ? 'flat: true' : '', dv ? 'divider: true' : '')})`);
    case 'photos': return w(`${ind(d)}THPhotoStrip(count: ${n.count})`);
    case 'timeline': return w(`${ind(d)}THTimeline(items: [${n.items.map((it) => `THTimelineItem(${ds(it.v)}, state: THTimelineState.${it.s}${it.sub ? `, subtitle: ${ds(it.sub)}` : ''})`).join(', ')}])`);
    case 'gap': return `${ind(d)}const SizedBox(${parent === 'row' ? 'width' : 'height'}: ${Number(n.n).toFixed(1)})`;
    case 'spacer': return `${ind(d)}const Spacer()`;
    case 'divider': return w(`${ind(d)}THDivider(${n.v ? `label: ${ds(n.v)}` : ''})`);
    case 'wordmark': return w(`${ind(d)}THWordmark(large: ${n.sz === 'lg'})`);
    default: return `${ind(d)}const SizedBox.shrink()`;
  }
}
const cls = (id) => id.split('_').map(cap).join('') + 'Screen';
function dartScreen(s) {
  const hasSpacer = s.body.some((c) => c.t === 'spacer');
  const bodyList = s.body.map((c, i) => dart(c, 5, s.body[i - 1], 'col')).join(',\n') + ',';
  const sticky = s.sticky ? `\n      stickyBar: THStickyBar(children: [\n${s.sticky.map((c) => dart(c, 4, null, 'row')).join(',\n')},\n      ]),` : '';
  const dock = s.dock ? `\n      dock: THDock(role: THDockRole.${s.dock}, active: ${s.nav ? `THDockTab.${s.nav}` : 'null'}),` : '';
  const bar = s.bar ? `\n      appBar: THAppBar(title: ${ds(s.bar.v)}${s.bar.sub ? `, subtitle: ${ds(s.bar.sub)}` : ''}),` : '';
  const colCode = `Column(\n          crossAxisAlignment: CrossAxisAlignment.stretch,\n          spacing: Space.s3,\n          children: [\n${bodyList}\n          ],\n        )`;
  return `// GENERATED from ast/screens.mjs (id: ${s.id}, route: ${s.route}). Do not edit by hand:
// change the AST and re-run \`node tools/build.mjs\`.
import 'package:flutter/material.dart';

import '../design_tokens.dart';
import '../th_widgets.dart';

class ${cls(s.id)} extends StatelessWidget {
  const ${cls(s.id)}({super.key});

  static const String route = ${ds(s.route)};

  @override
  Widget build(BuildContext context) {
    return THScaffold(${s.bg === 'hero' ? '\n      heroBackground: true,' : ''}${bar}${dock}${sticky}
      scrollable: ${!hasSpacer},
      body: ${colCode},
    );
  }
}
`;
}
