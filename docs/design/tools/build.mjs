// ───────────────────────── 1. contrast gate ─────────────────────────
const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
const lum = (h) => { const [r, g, b] = rgb(h).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const cr = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
const PAIRS = [['text', 'paper'], ['text', 'surface'], ['textSoft', 'paper'], ['textSoft', 'surface'], ['textSoft', 'surfaceAlt'], ['textBrand', 'paper'], ['brand', 'surface'], ['brand', 'tintBrand'],
  ['onBrand', 'brand'], ['onAccent', 'accent'], ['accentText', 'accentTint'], ['accentText', 'paper'], ['success', 'successTint'], ['danger', 'dangerTint'], ['onAvTradie', 'avTradie'],
  ['onHero', 'heroStart'], ['onHero', 'heroEnd'], ['heroGold', 'heroStart'], ['heroGold', 'heroEnd']];
const report = ['Contrast gate (WCAG AA 4.5:1)'];
for (const mode of ['light', 'dark']) for (const [f, b] of PAIRS) {
  const c = tokens.color[mode]; const r = cr(c[f], c[b]);
  report.push(`  ${r >= 4.5 ? 'PASS' : 'FAIL'}  ${mode.padEnd(5)} ${f} on ${b}  ${r.toFixed(2)}`);
  if (r < 4.5) errors.push(`contrast ${mode} ${f}/${b} ${r.toFixed(2)}`);
}
out['tokens/contrast-report.txt'] = report.join('\n') + '\n';

